"""Refresh ``monitor/cost/model_prices.json`` from LiteLLM's maintained price table.

LiteLLM publishes per-token prices (including prompt-cache read/write rates) for
every Anthropic model. We vendor only first-party Claude entries so cost analysis
works offline and results are reproducible.

    uv run python scripts/update_model_prices.py                 # download
    uv run python scripts/update_model_prices.py --from-file p.json
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path
from urllib.request import urlopen

SOURCE_URL = (
    "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
)
WEB_SEARCH_DEFAULT = 0.01
OUT = Path(__file__).resolve().parent.parent / "monitor" / "cost" / "model_prices.json"
KEEP_EXACT = {
    "input_cost_per_token",
    "output_cost_per_token",
    "cache_read_input_token_cost",
    "cache_creation_input_token_cost",
    "cache_creation_input_token_cost_above_1hr",
    "supports_fast_mode",
}


def _keep(key: str) -> bool:
    # long-context tiers, e.g. input_cost_per_token_above_100k_tokens
    return key in KEEP_EXACT or (
        "_above_" in key and key.endswith("k_tokens") and "batches" not in key
    )


def build(table: dict[str, dict]) -> dict:
    models: dict[str, dict] = {}
    for name, entry in sorted(table.items()):
        if not (name.startswith("claude-") and entry.get("litellm_provider") == "anthropic"):
            continue
        slim = {k: v for k, v in entry.items() if _keep(k)}
        search = (entry.get("search_context_cost_per_query") or {}).get(
            "search_context_size_medium"
        )
        # Anthropic bills web search at $10 per 1,000 requests on every model; LiteLLM omits the
        # field for some (e.g. Haiku 4.5), which would silently drop search fees from totals.
        slim["web_search_cost_per_request"] = search if search is not None else WEB_SEARCH_DEFAULT
        models[name] = slim
    return {
        "_meta": {
            "source": SOURCE_URL,
            "retrieved": date.today().isoformat(),
            "note": "USD per token. Generated by scripts/update_model_prices.py; do not edit by hand "
            "(use a MONITOR_PRICES override file instead).",
        },
        "models": models,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--from-file", help="read a local copy of the LiteLLM table instead of downloading"
    )
    args = ap.parse_args()
    if args.from_file:
        table = json.loads(Path(args.from_file).read_text())
    else:
        with urlopen(SOURCE_URL, timeout=60) as resp:  # nosec B310 - fixed https URL
            table = json.loads(resp.read())
    OUT.write_text(json.dumps(build(table), indent=1, sort_keys=True) + "\n")
    print(f"wrote {OUT} ({len(json.loads(OUT.read_text())['models'])} models)")


if __name__ == "__main__":
    main()
